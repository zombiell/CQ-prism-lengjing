#ifndef MOTOR_H
#define MOTOR_H

#include "main.h"
#include <stdint.h>

/* ============================================================
 * 电机编号 —— 与物理位置一一对应
 *   从车顶往下看，车头朝上
 * ============================================================ */
typedef enum {
    MOTOR_FL = 0,   /* 前左 Front-Left  */
    MOTOR_FR,       /* 前右 Front-Right */
    MOTOR_RL,       /* 后左 Rear-Left   */
    MOTOR_RR,       /* 后右 Rear-Right  */
    MOTOR_COUNT     /* 数量，用于循环   */
} motor_id_t;

/* ============================================================
 * PWM 参数 —— 必须和 CubeMX 里配置的 ARR 一致
 *   TIM2/TIM3 都设了 Period = 3599
 * ============================================================ */
#define MOTOR_PWM_MAX   3599u

/* 占空比安全上限
 * TT 马达堵转电流约 1~1.5A，DRV8833 每路持续 1.5A
 * 限到 85% 可以保护马达和驱动芯片不过热
 */
#define MOTOR_DUTY_LIMIT   0.85f

/* ============================================================
 * 软启动（斜坡升速）参数 —— 治"2 个轮能转、4 个轮一起不动"
 *
 * 原因：TT 马达的【启动电流】是稳态电流的好几倍。4 个轮子同时
 *       从 0 冲到目标值，电池瞬间被拉到欠压，驱动芯片进入
 *       欠压保护 → 四个轮子全都只"抖一下"。
 *
 * 对策：把起步过程拆成小步慢慢加上去，削平这个电流尖峰。
 *       每步多少取决于调用周期，本工程 main.c 是每 10ms 调一次。
 *
 * 注：目标值是 chassis.c 降额之后的 duty（直行时是 0.30），
 *     所以实际爬升时间约 150ms。
 * ============================================================ */
#define MOTOR_RAMP_UP      0.02f   /* 加速：每 10ms 加 2% */
#define MOTOR_RAMP_DOWN    0.08f   /* 减速：每 10ms 减 8% */

/* ============================================================
 * ★ 马达死区补偿 —— 治"命令了但轮子不转"
 *
 * 【实测依据】（架空逐个电机单独测）
 *      duty = 1.00  →  转
 *      duty = 0.60  →  不转
 *   同一个电机、同一套代码，只改 duty 数值 ⇒ 马达有【静摩擦死区】。
 *
 *   这就解释了"斜行能走、直行不走"：
 *      斜行每个轮子归一化后跑 1.00 → 能转
 *      直行每个轮子只有 0.60        → 卡死
 *
 * 【补偿方式】把命令 [0,1] 线性映射到 [DEADZONE, MAP_TOP]
 *      duty = 0.00 → 0.00   （0 就是停，不补偿）
 *      duty = 0.60 → 0.92
 *      duty = 1.00 → 1.00   ← 必须能到满速！
 *
 * ★ 重要：MAP_TOP 一定要留 1.00。
 *   第一次把 MAP_TOP 设成 0.90 时整车反而不动了 ——
 *   说明真实死区可能比估计的高，输出被压到 0.828 还落在死区里。
 *   所以上限必须允许"和实测能转的 1.00 一样"。
 *
 * 【调参】
 *   MOTOR_DEADZONE：已知 0.60 不转、1.00 转。
 *       0.80 = 当前值（比失败值高 33%，保守）
 *       如果低速起步仍卡住 → 调大到 0.85
 *       如果最低速太猛       → 调小到 0.75（但要确认还能起步）
 *   MOTOR_MAP_TOP：输出上限，固定 1.00（留给满速）
 * ============================================================ */
#define MOTOR_DEADZONE     0.80f   /* 能可靠克服静摩擦的最小占空比 */
#define MOTOR_MAP_TOP      1.00f   /* 补偿后的输出上限（必须能到满速） */

/* ============================================================
 * 接口
 * ============================================================ */

/* 初始化：启动 PWM 输出，并确保电机停转 */
void motor_init(void);

/* 设置单个电机
 *   duty > 0  正转，值越大越快
 *   duty < 0  反转
 *   duty = 0  滑行（两路都关，电机自由转动）
 *   范围 -1.0 ~ +1.0，超出会被限幅
 */
void motor_set(motor_id_t id, float duty);

/* 带软启动的单电机输出 —— chassis_mecanum 应该用这个而不是 motor_set
 * 内部把当前值以 MOTOR_RAMP_UP / MOTOR_RAMP_DOWN 的速度逐步逼近 target，
 * 再交给 motor_set 做限幅和写寄存器。
 * ⚠️ 必须在固定的周期里调用（本工程 10ms 一次），斜坡速度才有意义
 */
void motor_set_ramp(motor_id_t id, float target);

/* 清掉斜坡内部状态（当前值归 0）。
 * 只要绕过 motor_set_ramp 直接操作了 PWM，就必须调一次，
 * 否则斜坡的"内部记录值"和实际输出会对不上，下次起步会失灵。
 */
void motor_ramp_reset(void);

/* 全部滑行停止（松油门的感觉，惯性滑行） */
void motor_coast_all(void);

/* 全部刹车（电机制动，停得干脆，但冲击略大） */
void motor_brake_all(void);

#endif /* MOTOR_H */